def generate_zip_download(scan_data: Dict, files: List[Dict]) -> bytes:
    """Generate ZIP with fixed files + report"""
    buffer = io.BytesIO()
    language = scan_data.get("language", "python")
    ext = LANGUAGE_EXTENSIONS.get(language, ".txt")

    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        # Add fixed files
        for file in files:
            fname = file.get("filename", f"fixed_file{ext}")
            content = file.get("fixed_code") or file.get("original_code", "")
            if content:
                zf.writestr(f"fixed/{fname}", content)
            orig = file.get("original_code", "")
            if orig:
                zf.writestr(f"original/{fname}", orig)

        # Add markdown report
        md = generate_markdown_report(scan_data)
        zf.writestr("report/security_report.md", md.decode("utf-8"))

        # Add JSON data
        json_data = json.dumps({
            "scan_id": scan_data.get("scan_id"),
            "filename": scan_data.get("filename"),
            "language": language,
            "risk_level": scan_data.get("risk_level"),
            "vulnerabilities": scan_data.get("vulnerabilities", []),
            "timestamp": scan_data.get("timestamp"),
        }, indent=2, default=str)
        zf.writestr("report/scan_data.json", json_data)

        # Add README
        readme = f"""# AegisFlow Security Scan Results

## Scan Summary
- **File:** {scan_data.get('filename', 'unknown')}
- **Risk Level:** {scan_data.get('risk_level', 'UNKNOWN')}
- **Vulnerabilities Found:** {len(scan_data.get('vulnerabilities', []))}

## Contents
- `fixed/` — Fixed source files
- `original/` — Original source files
- `report/security_report.md` — Full security report
- `report/scan_data.json` — Raw scan data

## How to Use
1. Review `report/security_report.md` for full analysis
2. Compare `original/` vs `fixed/` to see changes
3. Test the fixed code before deploying

*Generated by AegisFlow v2.0*
"""
        zf.writestr("README.md", readme)

    return buffer.getvalue()


