LANGUAGE_EXTENSIONS = {
    "python": ".py", "javascript": ".js", "typescript": ".ts",
    "java": ".java", "go": ".go", "ruby": ".rb", "php": ".php",
    "c": ".c", "cpp": ".cpp", "swift": ".swift"
}


def generate_markdown_report(scan_data: Dict) -> bytes:
    """Generate a Markdown security report"""
    vulns = scan_data.get("vulnerabilities", [])
    filename = scan_data.get("filename", "unknown")
    language = scan_data.get("language", "unknown")
    risk = scan_data.get("risk_level", "UNKNOWN")
    timestamp = scan_data.get("timestamp", datetime.utcnow().isoformat())
    fixed_code = scan_data.get("fixed_code", "")
    original_code = scan_data.get("original_code", "")

    critical = [v for v in vulns if v.get("severity") == "CRITICAL"]
    high = [v for v in vulns if v.get("severity") == "HIGH"]
    medium = [v for v in vulns if v.get("severity") == "MEDIUM"]
    low = [v for v in vulns if v.get("severity") == "LOW"]

    md = f"""# 🛡️ AegisFlow Security Report

**File:** `{filename}`  
**Language:** {language.title()}  
**Risk Level:** {risk}  
**Scan Date:** {timestamp[:19].replace("T", " ")}  
**Total Vulnerabilities:** {len(vulns)}

---

## 📊 Summary

| Severity | Count |
|----------|-------|
| 🔴 Critical | {len(critical)} |
| 🟠 High | {len(high)} |
| 🟡 Medium | {len(medium)} |
| 🟢 Low | {len(low)} |

---

## 🔍 Vulnerabilities Found

"""
    for i, v in enumerate(vulns, 1):
        severity_emoji = {"CRITICAL": "🔴", "HIGH": "🟠", "MEDIUM": "🟡", "LOW": "🟢"}.get(v.get("severity"), "⚪")
        md += f"""### {i}. {severity_emoji} {v.get('type', 'Unknown')}

- **Severity:** {v.get('severity', 'UNKNOWN')}
- **Line:** {v.get('line', 'N/A')}
- **CWE:** {v.get('cwe_id', 'N/A')}
- **OWASP:** {v.get('owasp_id', 'N/A')}
- **Confidence:** {round(v.get('confidence', 0) * 100)}%
- **Description:** {v.get('description', 'No description')}

"""
        if v.get("code_snippet"):
            md += f"```{language}\n{v['code_snippet']}\n```\n\n"

    if original_code:
        md += f"""---

## 📄 Original Code

```{language}
{original_code}
```

"""

    if fixed_code:
        md += f"""---

## ✅ Fixed Code

```{language}
{fixed_code}
```

"""

    md += f"""---

## 🏢 About AegisFlow

AegisFlow is an AI-powered DevSecOps platform that automatically detects and fixes security vulnerabilities.

*Report generated by AegisFlow v2.0 — {datetime.utcnow().strftime('%Y-%m-%d')}*
"""
    return md.encode("utf-8")


def generate_pdf_report(scan_data: Dict) -> bytes:
    """Generate PDF using reportlab"""
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.colors import HexColor, black, white
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
        from reportlab.lib.units import cm
        from reportlab.lib.enums import TA_CENTER, TA_LEFT

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=A4,
                                 rightMargin=2*cm, leftMargin=2*cm,
                                 topMargin=2*cm, bottomMargin=2*cm)

        styles = getSampleStyleSheet()
        teal = HexColor("#06b6d4")
        coral = HexColor("#f97316")
        dark = HexColor("#0f172a")
        danger = HexColor("#ef4444")
        warn = HexColor("#f59e0b")
        success = HexColor("#10b981")
        gray = HexColor("#64748b")

        title_style = ParagraphStyle("Title", parent=styles["Title"],
                                      textColor=teal, fontSize=22, spaceAfter=6)
        h2_style = ParagraphStyle("H2", parent=styles["Heading2"],
                                   textColor=dark, fontSize=14, spaceAfter=4)
        body_style = ParagraphStyle("Body", parent=styles["Normal"],
                                     fontSize=10, spaceAfter=3, textColor=dark)

        vulns = scan_data.get("vulnerabilities", [])
        filename = scan_data.get("filename", "unknown")
        language = scan_data.get("language", "unknown")
        risk = scan_data.get("risk_level", "UNKNOWN")
        timestamp = scan_data.get("timestamp", datetime.utcnow().isoformat())[:19].replace("T", " ")

        story = []

        # Header
        story.append(Paragraph("🛡️ AegisFlow Security Report", title_style))
        story.append(Spacer(1, 0.3*cm))
        story.append(HRFlowable(width="100%", thickness=2, color=teal))
        story.append(Spacer(1, 0.3*cm))

        # Metadata table
        meta_data = [
            ["File", filename, "Language", language.title()],
            ["Risk Level", risk, "Scan Date", timestamp],
            ["Total Vulnerabilities", str(len(vulns)), "Scan ID", scan_data.get("scan_id", "N/A")[:16]],
        ]
        meta_table = Table(meta_data, colWidths=[3.5*cm, 5.5*cm, 3.5*cm, 5.5*cm])
        meta_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), HexColor("#f8fafc")),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("TEXTCOLOR", (0, 0), (0, -1), teal),
            ("TEXTCOLOR", (2, 0), (2, -1), teal),
            ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
            ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
            ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#e2e8f0")),
            ("PADDING", (0, 0), (-1, -1), 6),
        ]))
        story.append(meta_table)
        story.append(Spacer(1, 0.5*cm))

        # Summary
        story.append(Paragraph("📊 Vulnerability Summary", h2_style))
        critical = len([v for v in vulns if v.get("severity") == "CRITICAL"])
        high = len([v for v in vulns if v.get("severity") == "HIGH"])
        medium = len([v for v in vulns if v.get("severity") == "MEDIUM"])
        low = len([v for v in vulns if v.get("severity") == "LOW"])

        sum_data = [
            ["Severity", "Count", "Action Required"],
            ["🔴 CRITICAL", str(critical), "Immediate fix required"],
            ["🟠 HIGH", str(high), "Fix before deployment"],
            ["🟡 MEDIUM", str(medium), "Fix in next sprint"],
            ["🟢 LOW", str(low), "Fix when convenient"],
        ]
        sum_table = Table(sum_data, colWidths=[5*cm, 3*cm, 10*cm])
        sum_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), dark),
            ("TEXTCOLOR", (0, 0), (-1, 0), white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#e2e8f0")),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [white, HexColor("#f8fafc")]),
            ("PADDING", (0, 0), (-1, -1), 6),
            ("ALIGN", (1, 0), (1, -1), "CENTER"),
        ]))
        story.append(sum_table)
        story.append(Spacer(1, 0.5*cm))

        # Vulnerabilities
        if vulns:
            story.append(Paragraph("🔍 Detailed Findings", h2_style))
            for i, v in enumerate(vulns, 1):
                sev = v.get("severity", "UNKNOWN")
                sev_color = {"CRITICAL": danger, "HIGH": coral, "MEDIUM": warn, "LOW": success}.get(sev, gray)

                vuln_data = [
                    [f"{i}. {v.get('type', 'Unknown')}", f"Severity: {sev}"],
                    [f"Line: {v.get('line', 'N/A')} | CWE: {v.get('cwe_id', 'N/A')} | Confidence: {round(v.get('confidence', 0)*100)}%", ""],
                    [v.get("description", ""), ""],
                ]
                if v.get("code_snippet"):
                    vuln_data.append([f"Code: {v['code_snippet']}", ""])

                vtable = Table(vuln_data, colWidths=[14*cm, 4*cm])
                vtable.setStyle(TableStyle([
                    ("BACKGROUND", (0, 0), (-1, 0), sev_color),
                    ("TEXTCOLOR", (0, 0), (-1, 0), white),
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                    ("FONTSIZE", (0, 0), (-1, -1), 8),
                    ("GRID", (0, 0), (-1, -1), 0.3, HexColor("#e2e8f0")),
                    ("BACKGROUND", (0, 1), (-1, -1), HexColor("#f8fafc")),
                    ("PADDING", (0, 0), (-1, -1), 5),
                    ("SPAN", (0, 1), (1, 1)),
                    ("SPAN", (0, 2), (1, 2)),
                ]))
                story.append(vtable)
                story.append(Spacer(1, 0.3*cm))

        # Footer
        story.append(Spacer(1, 0.5*cm))
        story.append(HRFlowable(width="100%", thickness=1, color=teal))
        story.append(Paragraph(
            f"<i>Generated by AegisFlow v2.0 — AI-Powered Security Platform — {datetime.utcnow().strftime('%Y-%m-%d %H:%M')} UTC</i>",
            ParagraphStyle("Footer", parent=styles["Normal"], fontSize=8, textColor=gray, alignment=TA_CENTER)
        ))

        doc.build(story)
        return buffer.getvalue()

    except Exception as e:
        print(f"PDF generation error: {e}")
        # Return markdown as fallback
        return generate_markdown_report(scan_data)


