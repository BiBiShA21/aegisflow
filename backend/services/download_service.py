def generate_repo_zip_download(scan_data: Dict) -> bytes:
    """Generate ZIP with fixed files + report for repository"""
    buffer = io.BytesIO()

    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        # Add files (preserving directory structure)
        for file in scan_data.get("files", []):
            if file.get("total_found", 0) > 0:
                fname = file.get("filename", "unknown.txt")
                
                # If there's a fix, save both original and fixed
                fixed = file.get("fixed_code")
                orig = file.get("original_code")
                
                if fixed:
                    zf.writestr(f"fixed/{fname}", fixed)
                if orig:
                    zf.writestr(f"original/{fname}", orig)

        # Add markdown report
        md = generate_repo_markdown_report(scan_data)
        zf.writestr("report/repository_report.md", md.decode("utf-8"))

        # Add JSON data (excluding full code to keep it small)
        safe_scan_data = {k: v for k, v in scan_data.items() if k != "files"}
        safe_scan_data["files"] = [{"filename": f["filename"], "vulnerabilities": f["vulnerabilities"]} for f in scan_data.get("files", []) if f.get("total_found", 0) > 0]
        
        json_data = json.dumps(safe_scan_data, indent=2, default=str)
        zf.writestr("report/scan_data.json", json_data)

        # Add README
        readme = f"""# AegisFlow Repository Scan Results

## Scan Summary
- **Repository:** {scan_data.get('repo_name', 'unknown')}
- **Risk Level:** {scan_data.get('overall_risk', 'UNKNOWN')}
- **Total Vulns:** {scan_data.get('total_vulnerabilities', 0)}

## Contents
- `fixed/` — Fixed source files with directory structure preserved
- `original/` — Original vulnerable source files
- `report/repository_report.md` — Full security report
- `report/scan_data.json` — Raw scan data

*Generated by AegisFlow v2.0*
"""
        zf.writestr("README.md", readme)

    return buffer.getvalue()


